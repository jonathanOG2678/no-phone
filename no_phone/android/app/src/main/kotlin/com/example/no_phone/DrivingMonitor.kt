package com.example.no_phone

import android.Manifest
import android.app.PendingIntent
import android.content.Context
import android.content.Intent
import android.content.pm.PackageManager
import androidx.core.content.ContextCompat
import com.google.android.gms.location.ActivityRecognition
import com.google.android.gms.location.ActivityTransition
import com.google.android.gms.location.ActivityTransitionRequest
import com.google.android.gms.location.DetectedActivity
import android.util.Log

/* Creates and stores the following:
* - Activity Transition Request
* - Activity Transition "IN_VEHICLE" ENTER
* - Activity Transition "IN_VEHICLE" EXIT
* - PendingIntent that connects to ActivityTransitionReceiver.kt (Asks what we are looking for happens)
* - Registration request through ActivityRecognitionClient
*
*  This file is built from a guide on detecting when users start or stop activities:
* https://developer.android.com/develop/sensors-and-location/location/transitions
*  */

class DrivingMonitor(context: Context) {
    private companion object {
        const val TAG = "DrivingMonitor"
    }

    private  val appContext = context.applicationContext // Gets app context to allow Android features usage
    // Create and specify transition events of interest
    private val vehicleTransitions = listOf( // Creates list of interested events
        ActivityTransition.Builder().setActivityType(DetectedActivity.IN_VEHICLE).setActivityTransition(ActivityTransition.ACTIVITY_TRANSITION_ENTER).build(),
        ActivityTransition.Builder().setActivityType(DetectedActivity.IN_VEHICLE).setActivityTransition(ActivityTransition.ACTIVITY_TRANSITION_EXIT).build(),
    )
    private val transitionRequest = ActivityTransitionRequest(vehicleTransitions)

    private val activityRecognitionClient = ActivityRecognition.getClient(appContext) // Object that communicates registration and removal requests to Google Play Services
    // The following value was generated by ChatGPT as a way to create a PendingIntent object and attempt to communicate to Google Play Services for getting events
    private val transitionPendingIntent: PendingIntent =
        PendingIntent.getBroadcast(appContext,
            0,
            Intent(appContext, ActivityTransitionReceiver::class.java), // Tells app who the request is for)
            PendingIntent.FLAG_UPDATE_CURRENT or PendingIntent.FLAG_MUTABLE) // Sends the reroute to Google Play Services


    fun hasActivityRecognitionPermission(): Boolean {
        return ContextCompat.checkSelfPermission(appContext, Manifest.permission.ACTIVITY_RECOGNITION) == PackageManager.PERMISSION_GRANTED
    }

    fun enableMonitoring() {
        if (!hasActivityRecognitionPermission()) {
            Log.w(TAG, "Monitoring not enabled: permission missing")
            return
        }

        activityRecognitionClient.requestActivityTransitionUpdates(transitionRequest, transitionPendingIntent)
            .addOnSuccessListener {
                Log.d(TAG, "Monitoring Enabled")
            }
            .addOnFailureListener{
                Log.e(TAG, "Registration Failed", it)
            }

    }

    fun disableMonitoring() {
        if (!hasActivityRecognitionPermission()) {
            Log.w(TAG, "Monitoring not enabled: permission missing")
            return
        }

        // Remove PendingIntent

        activityRecognitionClient.removeActivityTransitionUpdates(transitionPendingIntent)
            .addOnSuccessListener {
                Log.d(TAG, "Monitoring Disabled")
            }
            .addOnFailureListener {
                Log.e(TAG, "Removal Failed", it)
            }
    }

}